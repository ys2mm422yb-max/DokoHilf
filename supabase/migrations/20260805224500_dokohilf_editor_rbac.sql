create or replace function public.dokohilf_role_for(target_user uuid)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select role
  from public.dokohilf_user_roles
  where user_id = target_user
    and active = true
  limit 1
$$;

create or replace function public.dokohilf_has_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.dokohilf_role_for(auth.uid()) = any(allowed_roles), false)
$$;

create or replace function public.dokohilf_can_write_guide_status(target_status text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case public.dokohilf_role_for(auth.uid())
    when 'admin' then target_status in ('draft', 'reviewed', 'approved', 'blocked')
    when 'editor' then target_status in ('draft', 'reviewed')
    else false
  end
$$;

revoke all on function public.dokohilf_role_for(uuid) from public, anon;
revoke all on function public.dokohilf_has_role(text[]) from public, anon;
revoke all on function public.dokohilf_can_write_guide_status(text) from public, anon;
grant execute on function public.dokohilf_role_for(uuid) to authenticated, service_role;
grant execute on function public.dokohilf_has_role(text[]) to authenticated, service_role;
grant execute on function public.dokohilf_can_write_guide_status(text) to authenticated, service_role;

create or replace function public.dokohilf_archive_guide_version()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.dokohilf_guide_versions (
    guide_id, slug, title, aliases, steps, troubleshooting, status, version,
    reviewed_at, reviewed_role, review_interval_days, review_due_at,
    change_note, changed_by
  ) values (
    old.id, old.slug, old.title, old.aliases, old.steps, old.troubleshooting,
    old.status, old.version, old.reviewed_at, old.reviewed_role,
    old.review_interval_days, old.review_due_at, old.change_note, auth.uid()
  );

  if tg_op = 'DELETE' then
    return old;
  end if;

  if row(
    new.slug, new.title, new.aliases, new.steps, new.troubleshooting,
    new.status, new.review_interval_days
  ) is distinct from row(
    old.slug, old.title, old.aliases, old.steps, old.troubleshooting,
    old.status, old.review_interval_days
  ) then
    new.version := old.version + 1;
  end if;

  new.updated_at := now();

  if new.reviewed_at is distinct from old.reviewed_at
     or new.review_interval_days is distinct from old.review_interval_days then
    new.review_due_at := case
      when new.reviewed_at is null then null
      else new.reviewed_at + make_interval(days => new.review_interval_days)
    end;
  end if;

  if new.status = 'approved' and old.status is distinct from 'approved' then
    new.approved_at := now();
    new.approved_by := auth.uid();
  elsif new.status is distinct from 'approved' then
    new.approved_at := null;
    new.approved_by := null;
  end if;

  return new;
end
$$;

revoke all on function public.dokohilf_archive_guide_version() from public, anon, authenticated;

drop trigger if exists dokohilf_guides_archive_version on public.dokohilf_guides;
create trigger dokohilf_guides_archive_version
before update or delete on public.dokohilf_guides
for each row execute function public.dokohilf_archive_guide_version();

