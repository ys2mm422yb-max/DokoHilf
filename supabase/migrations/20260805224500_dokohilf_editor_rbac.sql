-- Keine Client-Schreibrechte auf Rollen, Verlauf oder Audit. Änderungen laufen nur
-- kontrolliert über die JWT-geschützte Editor-Funktion beziehungsweise Administration.

create or replace function public.dokohilf_reject_public_signup(event jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(event->>'authentication_method', '') = 'invite' then
    return '{}'::jsonb;
  end if;

  return jsonb_build_object(
    'error', jsonb_build_object(
      'http_code', 403,
      'message', 'DokoHilf-Konten werden ausschließlich durch Einladung angelegt.'
    )
  );
end
$$;

grant usage on schema public to supabase_auth_admin;
grant execute on function public.dokohilf_reject_public_signup(jsonb) to supabase_auth_admin;
revoke execute on function public.dokohilf_reject_public_signup(jsonb) from public, anon, authenticated;

comment on function public.dokohilf_reject_public_signup(jsonb) is
  'Für den Supabase Before User Created Hook vorbereitet. Vor realem Rollout im Auth-Dashboard aktivieren.';
